/**
 * 입력 유효성 검사 정규표현식 패턴
 */
export const INPUT_VALIDATION_PATTERNS = {
  // 이름: 한글만 허용 (2-20자)
  NAME: /^[가-힣]{2,20}$/,

  // 생년월일: 6자리 숫자 (YYMMDD)
  BIRTH: /^\d{6}$/,

  // 휴대폰번호: 10-11자리 숫자 (하이픈 제외)
  PHONE_NUMBER: /^01[016789]\d{7,8}$/,

  // 인증번호: 6자리 숫자
  VERIFY_CODE: /^\d{6}$/,

  // 아이디: 영문+숫자 조합, 5-16자
  ID: /^[a-zA-Z0-9~!@#$%^&*()-_=+]{4,16}$/,

  // 비밀번호: 영문+숫자+특수문자 중 3가지 이상, 6-18자
  PASSWORD: /^(?=.*[a-zA-Z])(?=.*\d)(?=.*[!@#$%^&*()_+\-=[\]{};':"\\|,.<>?]).{6,18}$/,

  // 닉네임: 한글+영문+숫자+허용된 특수문자, 3-6자
  NICKNAME: /^[가-힣a-zA-Z0-9~!@#$%^&*()-_=+]{3,6}$/,

  // 이메일
  EMAIL: /^[a-zA-Z0-9._%+-]{5,20}$/,

  // 이메일: 일반적인 이메일 형식
  FULL_EMAIL: /^[a-zA-Z0-9._%+-]{5,20}@[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}$/,

  // 추천인 코드: 영문+숫자 조합 (예시)
  RECOMMEND_CODE: /^[A-Z0-9]{6,12}$/,

  // 주소: 주소 형식
  URL: /^((https?:\/\/)?([\w-]+(\.[\w-]+)+)(:\d+)?(\/[^\s]*)?)$/i
}
